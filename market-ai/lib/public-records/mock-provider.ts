function deed(
  date: string,
  grantor: string,
  grantee: string,
  price: number,
  type = "Warranty Deed"
): DeedRecord {
  return { date, grantor, grantee, salePrice: price, deedType: type };
}

function lien(
  type: string,
  holder: string,
  amount: number,
  date: string,
  status: "active" | "released" | "pending" = "active"
): Lien {
  return { type, holder, amount, recordedDate: date, status };
}

function improvement(
  type: string,
  yearBuilt?: number,
  sqft?: number,
  value?: number
): Improvement {
  return { type, yearBuilt, squareFeet: sqft, value };
}

