function matchesFilters(record: PublicRecordData, filters: PublicRecordSearchFilters): boolean {
  if (filters.state && record.state !== filters.state) return false;
  if (filters.county && !record.county.toLowerCase().includes(filters.county.toLowerCase())) return false;
  if (filters.minMarketValue !== undefined && record.marketValue < filters.minMarketValue) return false;
  if (filters.maxMarketValue !== undefined && record.marketValue > filters.maxMarketValue) return false;
  if (filters.minLotAcres !== undefined && record.lotSizeAcres < filters.minLotAcres) return false;
  if (filters.maxLotAcres !== undefined && record.lotSizeAcres > filters.maxLotAcres) return false;
  if (filters.taxStatus && record.taxStatus !== filters.taxStatus) return false;
  if (filters.isOutOfState !== undefined && record.isOutOfState !== filters.isOutOfState) return false;
  if (filters.zoning && !record.zoning.toLowerCase().includes(filters.zoning.toLowerCase())) return false;
  if (filters.ownerName && !record.ownerName.toLowerCase().includes(filters.ownerName.toLowerCase())) return false;
  if (filters.query) {
    const q = filters.query.toLowerCase();
    if (
      !record.ownerName.toLowerCase().includes(q) &&
      !record.propertyAddress.toLowerCase().includes(q) &&
      !record.parcelId.toLowerCase().includes(q) &&
      !record.county.toLowerCase().includes(q) &&
      !record.state.toLowerCase().includes(q)
    ) return false;
  }
  return true;
}

